//! Raw bindings to NVIDIA's cuObject libraries: the server
//! (`libcuobjserver`, feature `server`, on by default) and the client
//! (`libcuobjclient`, feature `client`).
//!
//! Both libraries are C++, so this crate compiles a small C wrapper over each
//! (`csrc/cuobject_sys.{h,cpp}` for the server, `csrc/cuobject_client.{h,cpp}`
//! for the client), and the build script generates these bindings from the
//! wrapper headers with bindgen. The wrappers never let a C++ exception cross
//! the boundary: every call returns `0` or a positive byte count on success
//! and a negative errno on failure.
//!
//! These declarations are unsafe to call; the [`cuobject`] crate wraps them in
//! a safe API.
//!
//! [`cuobject`]: https://docs.rs/cuobject
//!
//! # Linking
//!
//! The build script compiles the wrappers against `cuobjserver.h` and
//! `cuobjclient.h` and links `libcuobjserver`, or `libcuobjclient` and
//! `libcufile`, plus `libstdc++`. It looks in `$CUOBJSERVER_ROOT/{include,lib}`
//! and `$CUOBJCLIENT_ROOT/{include,lib}`, in the CUDA toolkit under
//! `$CUDA_HOME` (default `/usr/local/cuda`) and in the system paths. Linux
//! only. Generating the bindings needs libclang.

#![cfg_attr(not(test), no_std)]
#![allow(non_camel_case_types)]

// Generated by build.rs from the csrc/ wrapper headers, which document each
// item.
include!(concat!(env!("OUT_DIR"), "/bindings.rs"));

#[cfg(test)]
mod tests {
    #[allow(unused_imports)]
    use super::*;

    #[cfg(feature = "server")]
    #[test]
    fn links_the_server_and_reports_its_header_version() {
        // SAFETY: a pure function of compile-time constants.
        let version = unsafe { cuobj_version() };
        assert!(version >= 2000, "unexpected version {version}");
    }

    #[cfg(feature = "client")]
    #[test]
    fn links_the_client_and_reports_its_header_version() {
        // SAFETY: a pure function of compile-time constants.
        let version = unsafe { cuobj_client_version() };
        assert!(version >= 1000, "unexpected version {version}");
    }
}
